"""Report generation for Vantage findings (Markdown, HTML, and JSON).

Includes automatic secret redaction and Wilson interval presentation.
"""
from __future__ import annotations

import html
import json
import re
from typing import Any

from vantage.models.domain import RunSummary, TranscriptEntry


SECRET_PATTERNS = [
    re.compile(r"(?:api[_-]?key|secret|token|password|auth)[\"':\s=]+([A-Za-z0-9_\-\.]{12,})", re.IGNORECASE),
    re.compile(r"Bearer\s+([A-Za-z0-9_\-\.]{12,})", re.IGNORECASE),
    re.compile(r"(?:ghp|gho|rnd|tvly|gsk)_[A-Za-z0-9]{16,}", re.IGNORECASE),
]


def redact_secrets(text: str) -> str:
    """Sanitize transcripts to guarantee target secrets are never written to reports."""
    sanitized = text
    for pattern in SECRET_PATTERNS:
        sanitized = pattern.sub(r"[REDACTED_SECRET]", sanitized)
    return sanitized


def generate_json_report(summary: RunSummary) -> str:
    """Generate machine-readable JSON security assessment report."""
    raw_dict = summary.model_dump(mode="json")
    # Redact transcripts in the JSON export
    for finding in raw_dict.get("findings", []):
        for entry in finding.get("sample_transcript", []):
            if "content" in entry:
                entry["content"] = redact_secrets(entry["content"])
    return json.dumps(raw_dict, indent=2)


def generate_markdown_report(summary: RunSummary) -> str:
    """Generate Markdown executive security findings report."""
    md: list[str] = []
    md.append(f"# Vantage Security Assessment Report: {summary.target_name}")
    md.append(f"**Run ID:** `{summary.run_id}` | **Target Mode:** `{summary.target_mode}`")
    md.append(f"**Overall Risk Grade:** **{summary.risk_grade.value}** (ASR: {summary.overall_asr * 100:.1f}%)")
    md.append(f"**95% Wilson Confidence Interval:** [{summary.wilson_lower * 100:.1f}%, {summary.wilson_upper * 100:.1f}%]")
    md.append(f"**Total Scenarios Evaluated:** {summary.total_scenarios} | **Total Trials:** {summary.total_trials}")
    md.append(f"**Evaluation Duration:** {summary.duration_ms:.1f} ms\n")

    md.append("## OWASP Top 10 for Agentic Applications — Category Heatmap")
    md.append("| Category | Category Name | Scenarios | Trials | ASR | 95% Wilson Interval | Findings |")
    md.append("| :--- | :--- | :---: | :---: | :---: | :---: | :---: |")

    for cat in summary.category_scores:
        interval_str = f"[{cat.wilson_lower * 100:.1f}%, {cat.wilson_upper * 100:.1f}%]"
        asr_str = f"{cat.attack_success_rate * 100:.1f}%"
        md.append(
            f"| **{cat.category.value}** | {cat.category_name} | {cat.total_scenarios} | {cat.total_trials} | {asr_str} | {interval_str} | {cat.findings_count} |"
        )
    md.append("")

    md.append("## Vulnerability Findings & Canaries")
    if not summary.findings or all(f.successful_attacks == 0 for f in summary.findings):
        md.append("No active vulnerabilities or canaries triggered during this assessment. Target showed full resilience.")
    else:
        for f in summary.findings:
            if f.successful_attacks > 0:
                md.append(f"### [{f.severity.value}] {f.scenario_name} (`{f.scenario_id}`)")
                md.append(f"- **OWASP Category:** {f.category.value}")
                md.append(f"- **Attack Success Rate (ASR):** {f.attack_success_rate * 100:.1f}% ({f.successful_attacks}/{f.trials_run} trials)")
                md.append(f"- **Wilson Interval:** [{f.wilson_lower * 100:.1f}%, {f.wilson_upper * 100:.1f}%]")
                md.append(f"- **Canary Trigger:** `{f.canary_summary}`")
                md.append(f"- **Remediation:** {f.remediation_hint}\n")

                if f.sample_transcript:
                    md.append("<details><summary>View Trial Transcript</summary>\n")
                    md.append("```text")
                    for entry in f.sample_transcript:
                        clean_content = redact_secrets(entry.content)
                        md.append(f"[{entry.role.upper()}]: {clean_content}")
                    md.append("```\n</details>\n")

    md.append("---")
    md.append("*Generated by Vantage — Adversarial Testing & Security Assessment Framework for Autonomous AI Agents.*")
    return "\n".join(md)


